// ---------- feedback ----------
const API_BASE = import.meta.env.VITE_API_BASE || import.meta.env.VITE_API_URL || 'http://localhost:8000'

export async function submitFeedback({ question, answer, rating, comment, top_score, weak_match, not_found }) {
  try {
    const res = await apiFetch(`${API_BASE}/feedback`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ question, answer, rating, comment, top_score, weak_match, not_found }),
    })
    return res.ok
  } catch {
    return false
  }
}

// ---------- streaming SSE query ----------
/**
 * Connect to the /query/stream SSE endpoint and call callbacks as events arrive.
 *
 * @param {Object} params
 * @param {string} params.question
 * @param {number} params.top_k
 * @param {boolean} params.verify
 * @param {(data: Object) => void} params.onSources   — called with {sources, top_score, weak_match, rewritten_query}
 * @param {(token: string) => void} params.onToken     — called with each streamed token
 * @param {(data: Object) => void} params.onVerification — called with {verification}
 * @param {(data: Object) => void} params.onDone       — called with {answer}
 * @param {(error: string) => void} params.onError     — called on error
 * @returns {AbortController} — call .abort() to cancel the stream
 */
export function streamQuery({ question, top_k, verify, onSources, onToken, onVerification, onDone, onError }) {
  const controller = new AbortController()

  apiFetch(`${API_BASE}/query/stream`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ question, top_k, verify }),
    signal: controller.signal,
  })
    .then(async (res) => {
      if (!res.ok) {
        const body = await res.json().catch(() => ({}))
        throw new Error(typeof body.detail === 'string' ? body.detail : `Request failed (${res.status})`)
      }

      const reader = res.body.getReader()
      const decoder = new TextDecoder()
      let buffer = ''

      while (true) {
        const { value, done: streamDone } = await reader.read()
        if (streamDone) break
        buffer += decoder.decode(value, { stream: true })

        // Parse SSE events from the buffer
        const lines = buffer.split('\n')
        buffer = lines.pop() || '' // keep incomplete last line

        let currentEvent = null
        for (const line of lines) {
          if (line.startsWith('event: ')) {
            currentEvent = line.slice(7).trim()
          } else if (line.startsWith('data: ') && currentEvent) {
            try {
              const data = JSON.parse(line.slice(6))
              switch (currentEvent) {
                case 'sources':
                  onSources?.(data)
                  break
                case 'token':
                  onToken?.(data.token)
                  break
                case 'verification':
                  onVerification?.(data)
                  break
                case 'done':
                  onDone?.(data)
                  break
                case 'error':
                  onError?.(data.error || 'Unknown streaming error')
                  break
              }
            } catch {
              // Malformed JSON line, skip
            }
            currentEvent = null
          } else if (line === '') {
            currentEvent = null
          }
        }
      }
    })
    .catch((err) => {
      if (err.name !== 'AbortError') {
        onError?.(
          err instanceof TypeError
            ? `Cannot reach the API at ${API_BASE}. Check that the backend is running.`
            : err.message,
        )
      }
    })

  return controller
}

