// ---------- source filename -> readable title / date ----------
const MONTHS = ['January','February','March','April','May','June','July','August','September','October','November','December']

export function parseSource(fileName = '') {
  const base = fileName.replace(/\.pdf$/i, '')
  const m = base.match(/_on_(\d{1,2})_([A-Za-z]+)_(\d{4})$/)
  let year = null
  let date = null
  let titlePart = base
  if (m) {
    year = Number(m[3])
    date = `${m[1]} ${m[2]} ${m[3]}`
    titlePart = base.slice(0, m.index)
  }
  const title = titlePart.replace(/_/g, ' ').replace(/\bvs\b/i, 'v.')
  return { title, year, date, valid: !!m && MONTHS.includes(m[2]) }
}

// ---------- verification summary ----------
export function verdictOf(citation) {
  const s = citation.passage_support
  if (!s || !s.checked) return citation.existence?.exists_in_corpus ? 'unchecked' : 'missing'
  if (s.verdict === 'disputed') return 'disputed'
  return s.verdict || 'unclear'
}

export function summarize(verification) {
  const counts = { yes: 0, partial: 0, no: 0, disputed: 0, unclear: 0, unchecked: 0, missing: 0, unverifiable: 0 }
  if (!verification) return null
  for (const c of verification.citations || []) counts[verdictOf(c)] += 1
  counts.unverifiable = (verification.unverifiable_citations || []).length
  const total = (verification.citations || []).length + counts.unverifiable
  let level = 'none'
  if (total > 0) {
    if (counts.no || counts.disputed || counts.missing) level = 'low'
    else if (counts.partial || counts.unclear || counts.unverifiable || counts.unchecked) level = 'review'
    else level = 'high'
  }
  return { counts, total, level }
}

// ---------- put citation markers inside the answer text ----------
function escapeRe(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

// Split the answer into plain text + citation segments so each case name can
// be clicked and coloured by its verification verdict.
export function annotateAnswer(answer, verification) {
  if (!verification) return [{ text: answer }]
  const marks = []
  ;(verification.citations || []).forEach((c, i) => {
    const full = c.case_name
    const short = full.split(/\s+(?:vs\.?|v\.?)\s+/i)[0]
    for (const needle of [full, short]) {
      if (!needle || needle.length < 4) continue
      const re = new RegExp(escapeRe(needle), 'ig')
      let m
      while ((m = re.exec(answer))) marks.push({ start: m.index, end: m.index + m[0].length, kind: 'cited', index: i })
      if (marks.some((x) => x.index === i)) break
    }
  })
  ;(verification.unverifiable_citations || []).forEach((u, i) => {
    const re = new RegExp(escapeRe(u), 'ig')
    let m
    while ((m = re.exec(answer))) marks.push({ start: m.index, end: m.index + m[0].length, kind: 'unverifiable', index: i })
  })
  marks.sort((a, b) => a.start - b.start || b.end - a.end)
  const kept = []
  let cursor = 0
  for (const m of marks) {
    if (m.start < cursor) continue
    kept.push(m)
    cursor = m.end
  }
  const out = []
  cursor = 0
  for (const m of kept) {
    if (m.start > cursor) out.push({ text: answer.slice(cursor, m.start) })
    out.push({ text: answer.slice(m.start, m.end), kind: m.kind, index: m.index })
    cursor = m.end
  }
  if (cursor < answer.length) out.push({ text: answer.slice(cursor) })
  return out
}

// ---------- per-user history (localStorage) ----------
const historyKey = (userId) => `smart-courtroom:history:v2:${userId || 'guest'}`

export function loadHistory(userId) {
  try {
    return JSON.parse(localStorage.getItem(historyKey(userId))) || []
  } catch {
    return []
  }
}

export function saveHistory(items, userId) {
  try {
    localStorage.setItem(historyKey(userId), JSON.stringify(items.slice(0, 60)))
  } catch {
    /* storage full or blocked: history is a convenience, not required */
  }
}

// ---------- export ----------
export function toMarkdown(entry) {
  const lines = [`# ${entry.question}`, '', entry.answer, '', '## Sources retrieved', '']
  for (const s of entry.sources) lines.push(`- ${s.case_name} (${s.source_file}), score ${s.score.toFixed(3)}`)
  if (entry.verification?.citations?.length) {
    lines.push('', '## Citation verification', '')
    for (const c of entry.verification.citations) {
      const v = verdictOf(c)
      const reason = c.passage_support?.reason ? ` - ${c.passage_support.reason}` : ''
      lines.push(`- ${c.case_name}: ${v}${reason}`)
    }
  }
  if (entry.verification?.unverifiable_citations?.length) {
    lines.push('', 'Not found in corpus: ' + entry.verification.unverifiable_citations.join(', '))
  }
  lines.push('', '_Generated by Smart Courtroom. Verify against the original judgment before relying on it._')
  return lines.join('\n')
}

export function download(filename, text, type = 'text/markdown') {
  const url = URL.createObjectURL(new Blob([text], { type }))
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  a.click()
  URL.revokeObjectURL(url)
}

export function timeAgo(ts) {
  const s = Math.floor((Date.now() - ts) / 1000)
  if (s < 60) return 'just now'
  if (s < 3600) return `${Math.floor(s / 60)} min ago`
  if (s < 86400) return `${Math.floor(s / 3600)} h ago`
  return `${Math.floor(s / 86400)} d ago`
}

// ---------- passage highlighting ----------
const STOP = new Set('what when which whose where does that this with from under have been were will would could should about their there into than then them they also only other such upon shall must court case cases'.split(' '))

export function queryKeywords(query = '') {
  return [...new Set((query.toLowerCase().match(/[a-z]{4,}/g) || []).filter((w) => !STOP.has(w)))]
}

function tokens(text = '') {
  return new Set((text.toLowerCase().match(/[a-z]{5,}/g) || []).filter((w) => !STOP.has(w)))
}

// Split a passage into sentences and mark the one that overlaps most with the
// generated answer, so a reader can see where the answer likely came from.
export function highlightPassage(text = '', answer = '') {
  const parts = text.split(/(?<=[.;?!])\s+/).filter(Boolean)
  const answerTokens = tokens(answer)
  let bestIdx = -1
  let bestScore = 0
  parts.forEach((p, i) => {
    let score = 0
    for (const t of tokens(p)) if (answerTokens.has(t)) score += 1
    if (score > bestScore) { bestScore = score; bestIdx = i }
  })
  return parts.map((p, i) => ({ text: p, best: i === bestIdx && bestScore >= 3 }))
}

export function splitKeywords(text, keywords) {
  if (!keywords.length) return [{ text }]
  const re = new RegExp('(' + keywords.map(escapeRe).join('|') + ')', 'ig')
  return text.split(re).map((t, i) => ({ text: t, hit: i % 2 === 1 }))
}

export function passagesFor(citation, sources = []) {
  const files = citation.existence?.matched_files || []
  return sources.filter((s) => files.includes(s.source_file) || s.case_name === citation.case_name).slice(0, 2)
}

// ---------- suggested follow-ups (built from the retrieved cases, not by an LLM) ----------
export function followUps(entry) {
  if (!entry || entry.not_found) return []
  const out = []
  const disputed = (entry.verification?.citations || []).find((c) => verdictOf(c) === 'disputed')
  if (disputed) out.push(`What exactly did the court hold in ${disputed.case_name}?`)
  const seen = new Set(disputed ? [disputed.case_name] : [])
  for (const s of entry.sources) {
    if (seen.has(s.case_name) || out.length >= 3) continue
    seen.add(s.case_name)
    out.push(out.length === 0 ? `What was the final outcome in ${s.case_name}?` : `What were the facts of ${s.case_name}?`)
  }
  if (out.length < 3 && entry.sources.length) out.push('Which other judgments in the corpus deal with this issue?')
  return out.slice(0, 3)
}

// ---------- keyboard: arrow keys across a row of tabs ----------
export function tabKeys(e, ids, current, setCurrent, prefix) {
  const i = ids.indexOf(current)
  let next = null
  if (e.key === 'ArrowRight') next = ids[(i + 1) % ids.length]
  else if (e.key === 'ArrowLeft') next = ids[(i - 1 + ids.length) % ids.length]
  else if (e.key === 'Home') next = ids[0]
  else if (e.key === 'End') next = ids[ids.length - 1]
  if (!next) return
  e.preventDefault()
  setCurrent(next)
  setTimeout(() => document.getElementById(`${prefix}-tab-${next}`)?.focus(), 0)
}

